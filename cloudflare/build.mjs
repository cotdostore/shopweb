import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url));
const assets={};
for(const [route,file,type] of [
 ['/portal/admin','web/admin.html','text/html; charset=utf-8'],
 ['/portal/assets/admin.js','web/admin.js','text/javascript; charset=utf-8'],
 ['/portal/assets/portal.css','web/portal.css','text/css; charset=utf-8'],
 ['/portal/assets/duration.mjs','duration.mjs','text/javascript; charset=utf-8'],
 ['/portal/assets/Code.gs','apps-script/Code.gs','text/plain; charset=utf-8'],
 ['/portal/assets/appsscript.json','apps-script/appsscript.json','application/json; charset=utf-8'],
])assets[route]={body:await readFile(path.join(root,'portal',file),'utf8'),type};
// Publish a real customer page in the existing GitHub Pages site.
const githubDir=path.join(root,'../chatgpt');
await mkdir(githubDir,{recursive:true});
const customerHtml=await readFile(path.join(root,'portal/web/customer.html'),'utf8');
const customerJs=await readFile(path.join(root,'portal/web/customer.js'),'utf8');
const githubHtml=customerHtml
 .replace('<head>','<head><meta name="portal-api" content="https://cotdo-messenger-bot.kazuto121100.workers.dev/portal/api"><meta name="referrer" content="no-referrer"><meta http-equiv="Content-Security-Policy" content="default-src \'self\'; script-src \'self\'; style-src \'self\'; connect-src https://cotdo-messenger-bot.kazuto121100.workers.dev; img-src \'self\' data:; base-uri \'none\'; form-action \'self\'">')
 .replace('/portal/assets/portal.css','./portal.css').replace('/portal/assets/customer.js','./customer.js').replace('href="/chatgpt"','href="./"');
await writeFile(path.join(githubDir,'index.html'),githubHtml);
await writeFile(path.join(githubDir,'customer.js'),customerJs);
await writeFile(path.join(githubDir,'portal.css'),assets['/portal/assets/portal.css'].body);
await writeFile(path.join(root,'portal/assets.mjs'),'// Generated by cloudflare/build.mjs.\nexport default '+JSON.stringify(assets)+';\n');
const modules={};
for(const name of ['bot/worker.js','bot/commands.mjs','shared/prices-core.mjs','portal/index.mjs','portal/crypto.mjs','portal/parser.mjs','portal/duration.mjs','portal/assets.mjs'])modules[name]=await readFile(path.join(root,name),'utf8');
await mkdir(path.join(root,'dist'),{recursive:true});
await writeFile(path.join(root,'dist/modules.json'),JSON.stringify(modules));
console.log('Built '+Object.keys(modules).length+' Worker modules and '+Object.keys(assets).length+' web routes.');
